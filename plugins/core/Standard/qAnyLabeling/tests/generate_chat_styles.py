"""Embed the source Chat/VQA Qt styles without a runtime Python dependency.

Only pure style methods, theme dictionaries and string constants are executed.
The generated data is linked into the existing plugin on every platform.
"""
import argparse
import ast
import hashlib
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--upstream", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
base = args.upstream / "anylabeling/views/labeling"
theme = base / "utils/theme.py"
config = base / "chatbot/config.py"
style = base / "chatbot/style.py"
constants = {}
for path in (theme, config):
    for node in ast.parse(path.read_text()).body:
        if not isinstance(node, (ast.Assign, ast.AnnAssign)):
            continue
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, TypeError):
            continue
        for target in targets:
            if isinstance(target, ast.Name):
                constants[target.id] = value
namespace = dict(constants, Dict=dict, get_theme=lambda: namespace["THEME"])
methods = {}
for cls in ast.parse(style.read_text()).body:
    if not isinstance(cls, ast.ClassDef) or cls.name not in (
            "ChatbotDialogStyle", "ChatMessageStyle"):
        continue
    methods[cls.name] = {}
    for method in cls.body:
        if not isinstance(method, ast.FunctionDef) or not method.name.startswith("get_"):
            continue
        module = ast.Module(body=[method], type_ignores=[])
        exec(compile(ast.fix_missing_locations(module), str(style), "exec"), namespace)
        methods[cls.name][method.name] = namespace[method.name]
names = ["dialog", "menu", "main_splitter", "provider_button", "left_widget",
         "middle_widget", "chat_scroll_area", "image_preview", "button",
         "model_button", "settings_edit", "tab_widget", "settings_tabs",
         "slider", "right_splitter", "right_widget", "chat_container",
         "input_container", "input_frame", "message_input", "send_button"]
entries = [(name, methods["ChatbotDialogStyle"]["get_" + name + "_style"], ())
           for name in names]
for name, method, arguments in [
        ("message_bubble_user", "bubble", (True,)),
        ("message_bubble_assistant", "bubble", (False,)),
        ("message_content", "content_label", (False,)),
        ("message_content_error", "content_label", (True,)),
        ("message_role", "role_label", ()),
        ("message_role_background", "role_label_background", ()),
        ("message_button", "button", ()),
        ("message_editor", "edit_area", ()),
        ("message_edit_controls", "edit_button_wdiget", ()),
        ("message_resend", "resend_button", ()),
        ("message_cancel", "cancel_button", ()),
        ("message_save", "save_button", ())]:
    entries.append((name, methods["ChatMessageStyle"]["get_" + method + "_style"],
                    arguments))
lines = ["// Generated by tests/generate_chat_styles.py; do not edit.",
         "// Source: X-AnyLabeling-GGML, GPL-3.0 (see plugin upstream notices)."]
for path in (theme, config, style):
    lines.append("// %s SHA-256 %s" %
                 (path.relative_to(args.upstream),
                  hashlib.sha256(path.read_bytes()).hexdigest()))
for name, method, arguments in entries:
    values = []
    for mode in ("LIGHT", "DARK"):
        namespace["THEME"] = constants[mode]
        value = method(*arguments)
        assert ")chatstyle\"" not in value
        values.append('R"chatstyle(' + value + ')chatstyle"')
    lines.append('{"%s", %s, %s},' % (name, *values))
# VQA has separate constants and button colors. Keep its namespace isolated
# from Chat so a source configuration change cannot change another window.
vqa_config = base / "vqa/config.py"
vqa_style = base / "vqa/style.py"
vqa_namespace = dict(constants, Dict=dict)
vqa_namespace["get_theme"] = lambda: vqa_namespace["THEME"]
color_assignment = None
for node in ast.parse(vqa_config.read_text()).body:
    if not isinstance(node, ast.Assign):
        continue
    if any(isinstance(target, ast.Name) and target.id == "BUTTON_COLORS"
           for target in node.targets):
        color_assignment = node
    else:
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, TypeError):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name):
                vqa_namespace[target.id] = value
assert color_assignment is not None
for node in ast.parse(vqa_style.read_text()).body:
    if isinstance(node, ast.FunctionDef) and node.name.startswith("get_"):
        module = ast.Module(body=[node], type_ignores=[])
        exec(compile(ast.fix_missing_locations(module), str(vqa_style), "exec"),
             vqa_namespace)
for path in (vqa_config, vqa_style):
    lines.append("// %s SHA-256 %s" %
                 (path.relative_to(args.upstream),
                  hashlib.sha256(path.read_bytes()).hexdigest()))
vqa_entries = [(name, "get_" + name + "_style", ()) for name in
               ("filename_label", "image_label", "image_container",
                "page_input", "main_splitter", "panel_button", "button",
                "title_label", "message_label", "prompt_input")]
vqa_entries += [("dialog_button_" + variant, "get_dialog_button_style",
                 (variant, "medium")) for variant in
                ("primary", "secondary", "success", "danger")]
for name, method, arguments in vqa_entries:
    values = []
    for mode in ("LIGHT", "DARK"):
        vqa_namespace["THEME"] = constants[mode]
        module = ast.Module(body=[color_assignment], type_ignores=[])
        exec(compile(ast.fix_missing_locations(module), str(vqa_config), "exec"),
             vqa_namespace)
        value = vqa_namespace[method](*arguments)
        assert ")chatstyle\"" not in value
        values.append('R"chatstyle(' + value + ')chatstyle"')
    lines.append('{"vqa_%s", %s, %s},' % (name, *values))
text = "\n".join(lines) + "\n"
if args.check:
    assert args.output.read_text() == text, "Regenerate Chat source styles"
else:
    args.output.write_text(text)
print("Verified %d original light/dark style pairs" %
      (len(entries) + len(vqa_entries)))
