"""Generate the HTML5 named-reference data used by the OCR table codec.

The mapping is HTML standard data from Python's html.entities.html5:
https://html.spec.whatwg.org/multipage/named-characters.html
https://docs.python.org/3/license.html (PSF License Version 2).
Run from the repository root; no Python dependency is needed by the plugin.
"""
import argparse
import hashlib
import html.entities
import json
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument("--check", action="store_true")
parser.add_argument("--fixtures", type=Path,
                    help="Write transient inputs for native/upstream differential tests")
args = parser.parse_args()
lines = [
    "// HTML5 named character references; generated by",
    "// tests/generate_ppocr_html_entities.py from Python html.entities.html5.",
    "// HTML standard data: https://html.spec.whatwg.org/multipage/named-characters.html",
    "// Python distribution license: https://docs.python.org/3/license.html",
    "// Fields: name (including optional semicolon), first and second codepoint.",
]
for name, value in sorted(html.entities.html5.items()):
    points = [ord(char) for char in value]
    assert 1 <= len(points) <= 2
    points += [0] * (2 - len(points))
    lines.append('{"%s", 0x%x, 0x%x},' % (name, *points))
text = "\n".join(lines) + "\n"
if args.check:
    assert args.output.read_text() == text, "Regenerate the HTML5 reference mapping"
else:
    args.output.write_text(text)
if args.fixtures:
    inputs = []
    for name in sorted(html.entities.html5):
        inputs += ["<fcel>&" + name + "<nl>",
                   "<fcel>&" + name + "Suffix<nl>"]
    points = (list(range(161)) + list(range(0xfdd0, 0xfdf1)) +
              [0xd7ff, 0xd800, 0xdfff, 0xe000, 0xffff, 0x10000,
               0x1f600, 0x10fffd, 0x10fffe, 0x10ffff, 0x110000])
    for point in points:
        for number in (str(point), "x" + format(point, "x")):
            inputs += ["<fcel>&#" + number + "<nl>",
                       "<fcel>&#" + number + ";<nl>"]
    inputs += ["<fcel>&#9999999999999999999999999999;<nl>",
               "<fcel>&unknown;&notit;&amp=foo;&AMPfoo; &#-1;<nl>"]
    args.fixtures.write_text(json.dumps(inputs, ensure_ascii=True) + "\n")
print(json.dumps(dict(entries=len(html.entities.html5),
                      sha256=hashlib.sha256(text.encode()).hexdigest())))
