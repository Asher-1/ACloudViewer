#!/usr/bin/env python3
"""Regenerate tests/ocr/rec_crop_golden.txt from the upstream rec crop.

Each case runs PaddleX CropByPolys("quad").get_minarea_rect_crop's two steps
on a deterministic integer-hash image: the cv2.minAreaRect + cv2.boxPoints
re-fit of an int32 polygon, then get_rotate_crop_image's int() float32 edge
norms and cv2.warpPerspective(INTER_CUBIC, BORDER_REPLICATE). The rot90 that
follows is a pure transpose and is not recorded. The C++ port in
src/tasks/ocr/ocr_rec_crop.cpp must reproduce the box, the size and the crop
bytes (FNV-1a 64) exactly. Cases cover DB-style rotated rectangles, arbitrary
convex quads, polygons with interior/collinear points (convexHull), corners
outside the image (BORDER_REPLICATE) and crops above 65536 px, where the
parallel_for_ stripe split changes warpPerspective's block grid.

usage: gen_ocr_rec_crop_golden.py [output]
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import cv2
import numpy as np
from paddlex.inference.pipelines.components.common.crop_image_regions import (
    CropByPolys,
)

SEED = 20261013
CASES = 720
DEFAULT_OUTPUT = (Path(__file__).resolve().parents[1] / "tests" / "ocr" /
                  "rec_crop_golden.txt")


def hash_image(w: int, h: int, salt: int) -> np.ndarray:
    ys, xs, cs = np.mgrid[0:h, 0:w, 0:3].astype(np.uint64)
    v = (xs * np.uint64(73856093)) ^ (ys * np.uint64(19349663)) ^ (
        cs * np.uint64(83492791)) ^ np.uint64(salt)
    v = (v * np.uint64(2654435761)) & np.uint64(0xFFFFFFFF)
    return ((v >> np.uint64(13)) & np.uint64(255)).astype(np.uint8)


def fnv1a64(data: bytes) -> int:
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return value


def make_polygon(rng: np.random.Generator, w: int, h: int,
                 kind: int) -> np.ndarray:
    if kind == 0:  # DB box: rounded cv2.boxPoints of a rotated rectangle
        center = (rng.uniform(0, w), rng.uniform(0, h))
        size = (rng.uniform(4, w * 0.9), rng.uniform(4, h * 0.4))
        pts = cv2.boxPoints((center, size, rng.uniform(-90, 90)))
    elif kind == 5:  # crop above 98304 px: 2-5 parallel_for_ stripes
        center = (rng.uniform(w * 0.3, w * 0.7), rng.uniform(h * 0.3, h * 0.7))
        size = (rng.uniform(w * 0.6, w * 0.95), rng.uniform(h * 0.4, h * 0.9))
        pts = cv2.boxPoints((center, size, rng.uniform(-15, 15)))
    elif kind == 1:  # arbitrary convex quad
        cx, cy = rng.uniform(0, w), rng.uniform(0, h)
        angles = np.sort(rng.uniform(0, 2 * math.pi, 4))
        radii = rng.uniform(3, max(w, h) * 0.5, 4)
        pts = np.stack([cx + radii * np.cos(angles),
                        cy + radii * np.sin(angles)], 1)
    elif kind == 2:  # corners outside the image on any side
        pts = np.stack([rng.uniform(-0.3 * w, 1.3 * w, 4),
                        rng.uniform(-0.3 * h, 1.3 * h, 4)], 1)
    elif kind == 3:  # tall box (the caller's rot90 case)
        center = (rng.uniform(0, w), rng.uniform(0, h))
        size = (rng.uniform(4, w * 0.3), rng.uniform(h * 0.4, h * 0.9))
        pts = cv2.boxPoints((center, size, rng.uniform(-20, 20)))
    else:  # 5-8 points, some interior or collinear, through convexHull
        n = int(rng.integers(5, 9))
        x0, y0 = rng.uniform(0, w * 0.5), rng.uniform(0, h * 0.5)
        pts = np.stack([x0 + rng.uniform(0, w * 0.5, n),
                        y0 + rng.uniform(0, h * 0.5, n)], 1)
        pts[1] = (pts[0] + pts[2]) / 2
    return np.round(pts).astype(np.int32)


def main() -> int:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    rng = np.random.default_rng(SEED)
    crop = CropByPolys("quad")
    lines = [f"# generated by scripts/{Path(__file__).name}; opencv "
             f"{cv2.__version__}",
             "# iw ih salt n x0 y0 ... | b0x b0y b1x b1y b2x b2y b3x b3y | "
             "cw ch crop_fnv1a64"]
    written = 0
    while written < CASES:
        big = written % 12 == 11
        w = int(rng.integers(500, 900)) if big else int(rng.integers(16, 241))
        h = int(rng.integers(300, 600)) if big else int(rng.integers(16, 241))
        salt = int(rng.integers(0, 1 << 31))
        poly = make_polygon(rng, w, h, 5 if big else written % 5)
        rect = cv2.minAreaRect(poly)
        p = sorted(list(cv2.boxPoints(rect)), key=lambda x: x[0])
        a, d = (0, 1) if p[1][1] > p[0][1] else (1, 0)
        b, c = (2, 3) if p[3][1] > p[2][1] else (3, 2)
        box = np.array([p[a], p[b], p[c], p[d]])
        cw = int(max(np.linalg.norm(box[0] - box[1]),
                     np.linalg.norm(box[2] - box[3])))
        ch = int(max(np.linalg.norm(box[0] - box[3]),
                     np.linalg.norm(box[1] - box[2])))
        if cw < 1 or ch < 1:  # det's min_size filter never emits these
            continue
        img = hash_image(w, h, salt)
        out = crop.get_rotate_crop_image(img, box)
        if out.shape[0] != ch:  # undo the rot90 to record the warp itself
            out = np.rot90(out, -1)
        assert out.shape[:2] == (ch, cw)
        pts = " ".join(str(int(v)) for v in poly.reshape(-1))
        corners = " ".join(f"{float(v):.9g}" for v in box.reshape(-1))
        lines.append(f"{w} {h} {salt} {len(poly)} {pts} | {corners} | "
                     f"{cw} {ch} "
                     f"{fnv1a64(np.ascontiguousarray(out).tobytes()):016x}")
        written += 1
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {CASES} cases to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
