#!/usr/bin/env python3
"""Regenerate tests/ocr/db_postprocess_golden.txt from the upstream DB
post-process.

Each case renders a deterministic integer probability map (convex quads,
optionally ringed, with hash jitter that punches holes and ragged edges),
runs PaddleX DBPostProcess.boxes_from_bitmap (quad, fast score, no dilation:
the OCR pipeline configuration) and SortQuadBoxes, and records both box
lists. The C++ port in src/tasks/ocr/ocr_db_postprocess.cpp must reproduce
the raw order (OpenCV findContours RETR_LIST order), the int16 corners, the
scores and the sorted order exactly. destW/destH differ from the map size so
the half-to-even rescale is exercised.

usage: gen_db_postprocess_golden.py [output]
"""

from __future__ import annotations

import sys
from pathlib import Path

import cv2
import numpy as np
from paddlex.inference.models.text_detection.processors import DBPostProcess
from paddlex.inference.pipelines.components import SortQuadBoxes

SEED = 20261014
CASES = 400
DEFAULT_OUTPUT = (Path(__file__).resolve().parents[1] / "tests" / "ocr" /
                  "db_postprocess_golden.txt")


def hash_u32(xs: np.ndarray, ys: np.ndarray, salt: int) -> np.ndarray:
    v = (xs.astype(np.uint64) * np.uint64(73856093)) ^ (
        ys.astype(np.uint64) * np.uint64(19349663)) ^ np.uint64(salt)
    return ((v * np.uint64(2654435761)) & np.uint64(0xFFFFFFFF)) >> np.uint64(7)


def inside(quad: np.ndarray, xs: np.ndarray, ys: np.ndarray) -> np.ndarray:
    """Pixel (x, y) inside the convex integer quad (edges included)."""
    pos = np.ones(xs.shape, bool)
    neg = np.ones(xs.shape, bool)
    for i in range(4):
        ax, ay = int(quad[i][0]), int(quad[i][1])
        bx, by = int(quad[(i + 1) % 4][0]), int(quad[(i + 1) % 4][1])
        c = (bx - ax) * (ys - ay) - (by - ay) * (xs - ax)
        pos &= c >= 0
        neg &= c <= 0
    return pos | neg


def render(w: int, h: int, shapes: list, bg_mod: int, salt: int) -> np.ndarray:
    ys, xs = np.mgrid[0:h, 0:w].astype(np.int64)
    noise = hash_u32(xs, ys, salt)
    level = (noise % np.uint64(bg_mod)).astype(np.int64)
    for outer, inner, value, jitter in shapes:
        m = inside(outer, xs, ys)
        if inner is not None:
            m &= ~inside(inner, xs, ys)
        v = value - (noise % np.uint64(jitter)).astype(np.int64)
        level = np.where(m, np.maximum(level, v), level)
    return level.astype(np.float32) / np.float32(255.0)


def random_quad(rng, w, h, big):
    cx, cy = rng.uniform(-0.1 * w, 1.1 * w), rng.uniform(-0.1 * h, 1.1 * h)
    bw = rng.uniform(4, w * (0.9 if big else 0.4))
    bh = rng.uniform(3, h * (0.5 if big else 0.2))
    angle = rng.choice([0.0, 90.0, rng.uniform(-45, 45)])
    pts = cv2.boxPoints(((cx, cy), (bw, bh), angle))
    return np.round(pts).astype(np.int64), (cx, cy, bw, bh, angle)


def main() -> int:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    rng = np.random.default_rng(SEED)
    post = DBPostProcess(thresh=0.3, box_thresh=0.6, max_candidates=1000,
                         unclip_ratio=1.5, use_dilation=False,
                         score_mode="fast", box_type="quad")
    sort = SortQuadBoxes()
    lines = [f"# generated by scripts/{Path(__file__).name}; opencv "
             f"{cv2.__version__}",
             "# w h dw dh bg salt K [o0x o0y .. o3y ring i0x .. i3y value "
             "jitter]*K | n [q0x q0y .. q3y score]*n | sorted n [q..]*n"]
    total_boxes = 0
    for index in range(CASES):
        w, h = int(rng.integers(24, 201)), int(rng.integers(24, 201))
        scale = rng.choice([1.0, 1.37, 0.82, 2.0, 1.0 / 0.9777777777777777])
        dw, dh = max(1, int(round(w * scale))), max(1, int(round(h * scale)))
        k = int(rng.integers(1, 7))
        shapes, fields = [], []
        for _ in range(k):
            outer, (cx, cy, bw, bh, angle) = random_quad(rng, w, h, index % 4 == 0)
            inner = None
            if rng.random() < 0.25 and bw > 12 and bh > 9:
                inner = np.round(cv2.boxPoints(
                    ((cx, cy), (bw * 0.5, bh * 0.4), angle))).astype(np.int64)
            value = int(rng.integers(150, 256))
            jitter = int(rng.choice([1, 8, 48, 96]))
            shapes.append((outer, inner, value, jitter))
            ring = inner if inner is not None else np.zeros((4, 2), np.int64)
            fields += [*outer.reshape(-1).tolist(), int(inner is not None),
                       *ring.reshape(-1).tolist(), value, jitter]
        bg_mod = int(rng.choice([1, 40, 77]))
        salt = int(rng.integers(0, 1 << 31))
        pred = render(w, h, shapes, bg_mod, salt)
        boxes, scores = post.boxes_from_bitmap(pred, pred > 0.3, dw, dh, 0.6, 1.5)
        raw = " ".join(" ".join(str(int(v)) for v in b.reshape(-1)) +
                       f" {s:.17g}" for b, s in zip(boxes, scores))
        ordered = sort(boxes) if len(boxes) else []
        srt = " ".join(" ".join(str(int(v)) for v in b.reshape(-1))
                       for b in ordered)
        total_boxes += len(boxes)
        lines.append(f"{w} {h} {dw} {dh} {bg_mod} {salt} {k} "
                     f"{' '.join(map(str, fields))} | {len(boxes)} {raw} | "
                     f"{len(ordered)} {srt}")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {CASES} cases ({total_boxes} boxes) to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
