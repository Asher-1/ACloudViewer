#!/usr/bin/env python3
"""Regenerate tests/ocr/db_box_score_golden.txt from the upstream scorer.

Each case scores one quad with PaddleX DBPostProcess.box_score_fast on a
deterministic integer-hash probability map and records the cv2.fillPoly mask
(pixel count + FNV-1a 64 hash) the score is averaged over. The C++ port in
src/tasks/ocr/ocr_box_score.cpp must reproduce the mask bit-for-bit. Cases
cover DB-style rotated rectangles (cv2.boxPoints), arbitrary convex quads and
corners outside the map, which exercises cv::clipLine.

usage: gen_db_box_score_golden.py [output]
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import cv2
import numpy as np
from paddlex.inference.models.text_detection.processors import DBPostProcess

SEED = 20261012
CASES = 600
DEFAULT_OUTPUT = (Path(__file__).resolve().parents[1] / "tests" / "ocr" /
                  "db_box_score_golden.txt")


def prob_map(w: int, h: int) -> np.ndarray:
    ys, xs = np.mgrid[0:h, 0:w].astype(np.int64)
    v = ((xs * 73856093) ^ (ys * 19349663)) % 1000
    return v.astype(np.float32) / np.float32(1000.0)


def fnv1a64(data: bytes) -> int:
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return value


def make_quad(rng: np.random.Generator, w: int, h: int, kind: int) -> np.ndarray:
    if kind == 0:  # DB mini box: cv2.boxPoints of a rotated rectangle
        center = (rng.uniform(0, w), rng.uniform(0, h))
        size = (rng.uniform(2, w * 0.8), rng.uniform(2, h * 0.5))
        return cv2.boxPoints((center, size, rng.uniform(-90, 90))).astype(np.float32)
    if kind == 1:  # arbitrary convex quad around a center
        cx, cy = rng.uniform(0, w), rng.uniform(0, h)
        angles = np.sort(rng.uniform(0, 2 * math.pi, 4))
        radii = rng.uniform(1, max(w, h) * 0.6, 4)
        return np.stack([cx + radii * np.cos(angles),
                         cy + radii * np.sin(angles)], 1).astype(np.float32)
    # corners well outside the map on any side
    return np.stack([rng.uniform(-0.4 * w, 1.4 * w, 4),
                     rng.uniform(-0.4 * h, 1.4 * h, 4)], 1).astype(np.float32)


def main() -> int:
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    rng = np.random.default_rng(SEED)
    lines = [f"# generated by scripts/{Path(__file__).name}; opencv {cv2.__version__}",
             "# w h q0x q0y q1x q1y q2x q2y q3x q3y mask_count mask_fnv1a64 score"]
    for index in range(CASES):
        w, h = int(rng.integers(8, 97)), int(rng.integers(8, 97))
        box = make_quad(rng, w, h, index % 3)
        bitmap = prob_map(w, h)
        score = DBPostProcess.box_score_fast(None, bitmap, box)
        # The mask box_score_fast averages over, rebuilt with its own steps.
        xmin = max(0, min(math.floor(box[:, 0].min()), w - 1))
        xmax = max(0, min(math.ceil(box[:, 0].max()), w - 1))
        ymin = max(0, min(math.floor(box[:, 1].min()), h - 1))
        ymax = max(0, min(math.ceil(box[:, 1].max()), h - 1))
        shifted = box.copy()
        shifted[:, 0] -= xmin
        shifted[:, 1] -= ymin
        mask = np.zeros((ymax - ymin + 1, xmax - xmin + 1), dtype=np.uint8)
        cv2.fillPoly(mask, shifted.reshape(1, -1, 2).astype(np.int32), 1)
        corners = " ".join(f"{float(v):.9g}" for v in box.reshape(-1))
        lines.append(f"{w} {h} {corners} {int(mask.sum())} "
                     f"{fnv1a64(mask.tobytes()):016x} {score:.17g}")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {CASES} cases to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
